function generated(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [en, ar] of OBJECTIVES) out[en] = ar;

  // "Supports your objective(s): a, b" — ordered selections of up to four objectives (lower-cased labels).
  const walk = (picked: number[]) => {
    if (picked.length) {
      const en = picked.map((i) => OBJECTIVES[i][0].toLowerCase()).join(", ");
      const ar = picked.map((i) => OBJECTIVES[i][1]).join("، ");
      out[`Supports your objective${picked.length > 1 ? "s" : ""}: ${en}`] = `${picked.length > 1 ? "يدعم أهدافك" : "يدعم هدفك"}: ${ar}`;
    }
    if (picked.length === 4) return;
    for (let i = 0; i < OBJECTIVES.length; i++) if (!picked.includes(i)) walk([...picked, i]);
  };
  walk([]);

  for (const [en, ar] of INDUSTRIES) {
    out[en] = ar;
    out[`Strong fit for ${en.toLowerCase()}`] = `ملاءمة قوية لقطاع ${ar}`;
  }

  for (let tier = 0; tier <= 4; tier++) {
    out[`Designed for Tier ${tier} factories`] = `مصمَّم لمصانع المستوى ${tier}`;
    for (let target = 1; target <= 4; target++) out[`Reach Tier ${target} (currently Tier ${tier})`] = `بلوغ المستوى ${target} (حاليًا المستوى ${tier})`;
  }

  out["Recommended for Al Noor Textiles's current roadmap"] = "موصى به لخارطة الطريق الحالية للنور للمنسوجات";
  out["Recommended for Delta Precision Manufacturing's current roadmap"] = "موصى به لخارطة الطريق الحالية لدلتا للتصنيع الدقيق";

  for (const code of MACHINE_CODES) {
    out[`${code} bearing failure risk`] = `${code} خطر تعطل المحمل`;
    out[`${code} trending above baseline`] = `${code} يتجاوز خط الأساس`;
  }
  return out;
}

