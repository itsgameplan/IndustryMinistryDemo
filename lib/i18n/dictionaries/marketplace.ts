/**
 * Build-log lines in lib/data/deployables.ts are composed from catalogue fields
 * (`${label}…`, `${label} complete`, `Preparing: ${deliverable}`, `${name} workspace ready`).
 * Derive their Arabic from the entries above so the keys always match the generated text.
 */
function deployLogEntries(): Record<string, string> {
  const out: Record<string, string> = {};
  const ar = (s: string) => base[s] ?? s;
  for (const s of SERVICE_LIST) {
    for (const { label } of [...s.buildAgents, { label: "Publishing workspace" }]) {
      out[`${label}…`] = `${ar(label)}…`;
      out[`${label} complete`] = `اكتمل: ${ar(label)}`;
    }
    for (const d of s.demoDeliverables) out[`Preparing: ${d}`] = `جارٍ التحضير: ${ar(d)}`;
    out[`${s.name} workspace ready`] = `مساحة عمل «${s.nameAr}» جاهزة`;
  }
  return out;
}

export const marketplace: Record<string, string> = { ...base, ...deployLogEntries() };
